export function getTemplateById(id: string): QRTemplate | undefined {
  return QR_TEMPLATES.find(template => template.id === id);
}

export function getTemplatesByCategory(category: string): QRTemplate[] {
  if (category === 'all') return QR_TEMPLATES;
  return QR_TEMPLATES.filter(template => template.category === category);
}

export function getPremiumTemplates(): QRTemplate[] {
  return QR_TEMPLATES.filter(template => template.isPremium);
}

export function getFreeTemplates(): QRTemplate[] {
  return QR_TEMPLATES.filter(template => !template.isPremium);
}
